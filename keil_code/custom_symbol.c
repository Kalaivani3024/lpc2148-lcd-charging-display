#include <lpc21xx.h>
#include "LCD.h"
typedef unsigned char u8;

u8 cgram_lut[] = {0x0e,0x1b,0x11,0x11,0x11,0x11,0x1f,0x00,
                  0x0e,0x1b,0x11,0x11,0x11,0x1f,0x1f,0x00,
                  0x0e,0x1b,0x11,0x11,0x1f,0x1f,0x1f,0x00,
                  0x0e,0x1b,0x11,0x1f,0x1f,0x1f,0x1f,0x00,
                  0x0e,0x1b,0x1f,0x1f,0x1f,0x1f,0x1f,0x00,
                  0x0e,0x1f,0x1f,0x1f,0x1f,0x1f,0x1f,0x00};

void cgram_write(unsigned char);
int main()
{
	char symbol=0;
	lcd_config();

	cgram_write(48);
	while(symbol<6)
	{
	lcd_cmd(0x80);
	lcd_data(symbol++);
		delay_ms(500);
	if(symbol==6)
      symbol=0;
}	
}
void cgram_write(unsigned char nbytes)
{
	unsigned char i;
	lcd_cmd(0x40);
	for(i=0;i<nbytes;i++)
	lcd_data(cgram_lut[i]);
}
